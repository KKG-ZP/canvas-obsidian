import esbuild from "esbuild";
import process from "process";
import { readFile, writeFile } from "node:fs/promises";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

function scopeMantineCss(css) {
	// :where() keeps these resets at element specificity so Mantine's own
	// button/input rules still win. A plain .cursor-canvas-host button
	// selector overrides line-height and clips CJK glyphs against the border.
	return css
		.replaceAll("body{", ".cursor-canvas-host{")
		.replaceAll(
			"input,button,textarea,select{",
			":where(.cursor-canvas-host) input,:where(.cursor-canvas-host) button,:where(.cursor-canvas-host) textarea,:where(.cursor-canvas-host) select{",
		)
		.replaceAll(
			"button,select{",
			":where(.cursor-canvas-host) button,:where(.cursor-canvas-host) select{",
		)
		.replaceAll(
			"*,*:before,*:after{",
			":where(.cursor-canvas-host),:where(.cursor-canvas-host) *,:where(.cursor-canvas-host) *:before,:where(.cursor-canvas-host) *:after{",
		);
}

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: {
		main: "src/main.ts",
		styles: "src/styles.css",
	},
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outdir: ".",
	entryNames: "[name]",
	minify: prod,
	platform: "browser",
	define: {
		"process.env.NODE_ENV": JSON.stringify(prod ? "production" : "development"),
		"import.meta.env.DEV": JSON.stringify(!prod),
		"import.meta.env.PROD": JSON.stringify(prod),
	},
	plugins: [
		{
			name: "scope-mantine-css",
			setup(build) {
				build.onEnd(async (result) => {
					if (result.errors.length > 0) {
						return;
					}
					const css = await readFile("styles.css", "utf8");
					await writeFile("styles.css", scopeMantineCss(css));
				});
			},
		},
	],
});

if (prod) {
	await context.rebuild();
	await context.dispose();
	process.exit(0);
}

await context.watch();
